    fun score(event:PfraEvent, age:Int, sex:PfraSex, raw:Int): Double {
        val col = ageBand(age)*2 + if(sex == PfraSex.MALE) 0 else 1
        val rows = when(event){
            PfraEvent.PUSH_UP -> push_up
            PfraEvent.HAND_RELEASE_PUSH_UP -> hand_release_push_up
            PfraEvent.SIT_UP -> sit_up
            PfraEvent.CROSS_LEG_REVERSE_CRUNCH -> cross_leg_reverse_crunch
            PfraEvent.FOREARM_PLANK -> forearm_plank
            PfraEvent.TWO_MILE_RUN -> two_mile_run
            PfraEvent.HAMR -> hamr
        }
        val higherIsBetter = event != PfraEvent.TWO_MILE_RUN
        for (row in rows) {
            val threshold = row.values[col]
            if ((higherIsBetter && raw >= threshold) || (!higherIsBetter && raw <= threshold)) return row.points
        }
        return 0.0
    }
    fun parseTime(value:String): Int? {
        val p=value.trim().split(":")
        return when(p.size){ 2 -> p[0].toIntOrNull()?.let{m->p[1].toIntOrNull()?.let{s->m*60+s}}; 1 -> p[0].toIntOrNull(); else -> null }
    }
    fun walkMaxSeconds(age:Int, sex:PfraSex): Int {
        val band = when { age < 30 -> 0; age < 40 -> 1; age < 50 -> 2; age < 60 -> 3; else -> 4 }
        val male = intArrayOf(16*60+16,16*60+18,16*60+23,16*60+40,16*60+58)
        val female = intArrayOf(17*60+22,17*60+28,17*60+49,18*60+11,18*60+53)
        return if(sex==PfraSex.MALE) male[band] else female[band]
    }
    fun formatSeconds(seconds:Int): String = "%d:%02d".format(seconds/60, seconds%60)
